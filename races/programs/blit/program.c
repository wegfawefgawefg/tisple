static uint8_t saved[SPRITES][16 * 3];

static void save_and_draw(uint8_t i) {
    uint8_t *p = screen + sprites[i].y * ROW + (sprites[i].x >> 3);
    const uint8_t *shape = SHAPES + sprites[i].shape * 64;
    uint8_t *save = saved[i];
    uint8_t shift = sprites[i].x & 7;
    uint8_t back = 8 - shift;
    uint8_t r, i0, i1, o0, o1;
    for (r = 0; r < 16; r++) {
        i0 = shape[0];
        i1 = shape[1];
        o0 = shape[2];
        o1 = shape[3];
        save[0] = p[0];
        save[1] = p[1];
        save[2] = p[2];
        p[0] = (p[0] & ~(o0 >> shift)) | (i0 >> shift);
        p[1] = (p[1] & ~((uint8_t)(o0 << back) | (o1 >> shift))) |
               (uint8_t)(i0 << back) | (i1 >> shift);
        p[2] = (p[2] & ~(uint8_t)(o1 << back)) | (uint8_t)(i1 << back);
        shape += 4;
        save += 3;
        p += ROW;
    }
}

static void restore(uint8_t i) {
    uint8_t *p = screen + sprites[i].y * ROW + (sprites[i].x >> 3);
    uint8_t *save = saved[i];
    uint8_t r;
    for (r = 0; r < 16; r++) {
        p[0] = save[0];
        p[1] = save[1];
        p[2] = save[2];
        save += 3;
        p += ROW;
    }
}

/* x and y stay in 0..MAX: a step past an edge wraps to a big byte, and turns back */
static void move(uint8_t i) {
    uint8_t x = sprites[i].x + sprites[i].dx;
    uint8_t y = sprites[i].y + sprites[i].dy;
    if (x > MAX_X) {
        sprites[i].dx = -sprites[i].dx;
        x = sprites[i].x + sprites[i].dx;
    }
    if (y > MAX_Y) {
        sprites[i].dy = -sprites[i].dy;
        y = sprites[i].y + sprites[i].dy;
    }
    sprites[i].x = x;
    sprites[i].y = y;
}

int main(void) {
    uint8_t f, i;
    uint16_t n, sum_a = 0, sum_b = 0;
    for (i = 0; i < SPRITES; i++) save_and_draw(i);
    for (f = 0; f < FRAMES; f++) {
        i = SPRITES;
        while (i != 0) {
            i--;
            restore(i);
        }
        for (i = 0; i < SPRITES; i++) move(i);
        for (i = 0; i < SPRITES; i++) save_and_draw(i);
    }
    for (n = 0; n < ROW * 192; n++) {
        sum_a += screen[n];
        sum_b += sum_a;
    }
    checksum = sum_a ^ sum_b;
    return 0;
}
