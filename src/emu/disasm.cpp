struct DasmState {
    const uint8_t* mem = nullptr;
    uint16_t next = 0;
    std::string text;
};

uint8_t DasmIn(void* user) {
    DasmState* state = static_cast<DasmState*>(user);
    return state->mem[state->next++];
}

void DasmOut(char c, void* user) {
    static_cast<DasmState*>(user)->text.push_back(c);
}

