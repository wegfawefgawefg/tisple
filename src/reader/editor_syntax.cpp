// --- VS Code (TextMate, Oniguruma regexes) ---

const char* const kTmBefore = R"re((?<![^\s()'`,@]))re";
const char* const kTmAfter = R"re((?![^\s()";'`,]))re";
const char* const kTmQualifier = R"re((?:[^\s()";'`,]*[./])?)re";

std::string TmEscape(const char* word) {
    std::string out;
    for (const char* c = word; *c; c++) {
        if (std::string_view(".+*?()[]{}|^$\\/").find(*c) != std::string_view::npos) {
            out += '\\';
        }
        out += *c;
    }
    return out;
}

std::string TmWords(std::span<const char* const> words) {
    std::string alts;
    for (const char* word : words) {
        alts += (alts.empty() ? "" : "|") + TmEscape(word);
    }
    return std::string(kTmBefore) + "(?:" + alts + ")" + kTmAfter;
}

std::string JsonString(const std::string& text) {
    std::string out = "\"";
    for (char c : text) {
        if (c == '"' || c == '\\') {
            out += '\\';
        }
        out += c;
    }
    return out + "\"";
}

std::string TmRule(const char* key, const char* scope, const std::string& match) {
    std::string out = "    " + JsonString(key) + ": {\n";
    if (scope) {
        out += "      \"name\": " + JsonString(scope) + ",\n";
    }
    out += "      \"match\": " + JsonString(match) + "\n    }";
    return out;
}

// --- Neovim / Vim (magic regexes, '{' as the pattern delimiter: no pattern uses it) ---

const char* const kVimBefore = R"re(\%(^\|[[:space:]()'`,@]\)\@<=)re";
const char* const kVimAfter = R"re(\%($\|[[:space:]()";'`,]\)\@=)re";
const char* const kVimQualifier = R"re(\%([^[:space:]()";'`,]*[./]\)\?)re";

std::string VimEscape(const char* word) {
    std::string out;
    for (const char* c = word; *c; c++) {
        if (std::string_view(".*~[]\\^$").find(*c) != std::string_view::npos) {
            out += '\\';
        }
        out += *c;
    }
    return out;
}

std::string VimWords(std::span<const char* const> words) {
    std::string alts;
    for (const char* word : words) {
        alts += (alts.empty() ? "" : "\\|") + VimEscape(word);
    }
    return std::string(kVimBefore) + "\\%(" + alts + "\\)" + kVimAfter;
}

std::string VimMatch(const char* group, const std::string& pattern) {
    return std::string("syn match ") + group + " {" + pattern + "{\n";
}

