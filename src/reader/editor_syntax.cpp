std::string VsCodeGrammar() {
    std::string before = kTmBefore;
    std::string after = kTmAfter;
    std::string pascal = before + kTmQualifier + "[A-Z][A-Za-z0-9]*[a-z][A-Za-z0-9]*#?" + after;
    std::string caps = before + kTmQualifier + "[A-Z][A-Z0-9_]*#?" + after;
    std::string number = before + "-?(?:0[xX][0-9A-Fa-f]+|0[bB][01]+|[0-9]+)" + after;

    const char* order[] = {"comment", "string",   "number", "keyword", "quote",  "special", "type",
                           "builtin", "constant", "pascal", "caps",    "symbol", "paren"};
    std::string out = "{\n";
    out += "  \"$comment\": \"Generated by `tisple gen-editors editors` from "
           "src/reader/keywords.cpp; do not edit.\",\n";
    out += "  \"name\": \"Tisple\",\n  \"scopeName\": \"source.tisple\",\n  \"patterns\": [\n";
    for (std::size_t i = 0; i < std::size(order); i++) {
        out += std::string("    { \"include\": \"#") + order[i] + "\" }";
        out += i + 1 < std::size(order) ? ",\n" : "\n";
    }
    out += "  ],\n  \"repository\": {\n";
    out += TmRule("comment", "comment.line.semicolon.tisple", ";.*$") + ",\n";
    out += "    \"string\": {\n"
           "      \"name\": \"string.quoted.double.tisple\",\n"
           "      \"begin\": \"\\\"\",\n"
           "      \"end\": \"\\\"|$\",\n"
           "      \"patterns\": [\n"
           "        { \"name\": \"constant.character.escape.tisple\", "
           "\"match\": \"\\\\\\\\(?:x[0-9A-Fa-f]{2}|.)\" }\n"
           "      ]\n"
           "    },\n";
    out += TmRule("number", "constant.numeric.tisple", number) + ",\n";
    out += TmRule("keyword", "entity.other.attribute-name.keyword.tisple",
                  before + ":[^\\s()\";'`,]+") +
           ",\n";
    out += TmRule("quote", "keyword.operator.quote.tisple", ",@|['`,]") + ",\n";
    out += TmRule("special", "keyword.control.tisple", TmWords(SpecialForms())) + ",\n";
    out += TmRule("type", "storage.type.tisple", TmWords(TypeNames())) + ",\n";
    out += TmRule("builtin", "support.function.builtin.tisple", TmWords(Builtins())) + ",\n";
    out += TmRule("constant", "constant.language.tisple", TmWords(ConstantNames())) + ",\n";
    out += TmRule("pascal", "entity.name.type.tisple", pascal) + ",\n";
    out += TmRule("caps", "variable.other.constant.tisple", caps) + ",\n";
    out += TmRule("symbol", nullptr, before + "[^\\s()\";'`,]+") + ",\n";
    out += TmRule("paren", "punctuation.section.parens.tisple", "[()]") + "\n";
    out += "  }\n}\n";
    return out;
}

std::string NvimSyntax() {
    std::string before = kVimBefore;
    std::string after = kVimAfter;
    std::string out;
    out += "\" Vim syntax file\n"
           "\" Language: Tisple ][\n"
           "\" Generated by `tisple gen-editors editors` from src/reader/keywords.cpp; do not "
           "edit.\n\n"
           "if exists(\"b:current_syntax\")\n  finish\nendif\n\n"
           "syn case match\n\n";
    // later matches win at the same position, so the general ones come first
    out += VimMatch("tisplePascal",
                    before + kVimQualifier + "\\u[[:alnum:]]*\\l[[:alnum:]]*#\\=" + after);
    out += VimMatch("tispleCaps", before + kVimQualifier + "\\u[[:upper:][:digit:]_]*#\\=" + after);
    out += VimMatch("tispleType", VimWords(TypeNames()));
    out += VimMatch("tispleBuiltin", VimWords(Builtins()));
    out += VimMatch("tispleConstant", VimWords(ConstantNames()));
    out += VimMatch("tispleSpecial", VimWords(SpecialForms()));
    out +=
        VimMatch("tispleNumber", before + "-\\=\\%(0[xX]\\x\\+\\|0[bB][01]\\+\\|\\d\\+\\)" + after);
    out += VimMatch("tispleKeyword", before + ":[^[:space:]()\";'`,]\\+");
    out += VimMatch("tispleQuote", ",@\\|['`,]");
    out += VimMatch("tispleParen", "[()]");
    out += "syn match tispleEscape contained {\\\\\\%(x\\x\\x\\|.\\){\n";
    out += "syn region tispleString start={\"{ skip={\\\\\\\\\\|\\\\\"{ end={\"{ oneline "
           "contains=tispleEscape\n";
    out += "syn match tispleComment {;.*${\n\n";
    out += "hi def link tisplePascal Type\n"
           "hi def link tispleCaps Constant\n"
           "hi def link tispleType Type\n"
           "hi def link tispleBuiltin Function\n"
           "hi def link tispleConstant Boolean\n"
           "hi def link tispleSpecial Keyword\n"
           "hi def link tispleNumber Number\n"
           "hi def link tispleKeyword Label\n"
           "hi def link tispleQuote Special\n"
           "hi def link tispleParen Delimiter\n"
           "hi def link tispleEscape SpecialChar\n"
           "hi def link tispleString String\n"
           "hi def link tispleComment Comment\n\n"
           "let b:current_syntax = \"tisple\"\n";
    return out;
}

