#!/usr/bin/env python3
"""Writes the player's own Apple II font (src/machine/font.cpp) as a script for the page, so
its buttons and bar letter in the machine's own 5x7 dots.

    web/font.py OUT.js

APPLE_FONT[ch] is seven numbers, one a row, bit 4 the leftmost of five dots. MouseText's
arrows come as the characters the page's labels use for them (the old configs' &larr; and the
like): seven rows of the glyph's middle five dots.
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FONT_CPP = os.path.join(os.path.dirname(HERE), "src", "machine", "font.cpp")

# MouseText glyph numbers and the characters that stand for them in labels
ARROWS = {8: "←", 21: "→", 11: "↑", 10: "↓"}


def rows_of(block):
    return re.findall(r'"([.#]+)"', block)


def main():
    text = open(FONT_CPP).read()
    ascii_part = text[text.index("kGlyphs[96][7]"):text.index("kMouseText[32][8]")]
    mouse_part = text[text.index("kMouseText[32][8]"):]
    glyphs = re.findall(r"\{((?:\s*\"[.#]{5}\",?){7})\s*\}", ascii_part)
    mouse = re.findall(r"\{((?:\s*\"[.#]{7}\",?){8})\s*\}", mouse_part)
    if len(glyphs) != 96 or len(mouse) != 32:
        sys.exit(f"font.cpp: {len(glyphs)} glyphs, {len(mouse)} MouseText; want 96 and 32")
    font = {}
    for i, block in enumerate(glyphs):
        font[chr(0x20 + i)] = [int(r.replace(".", "0").replace("#", "1"), 2) for r in rows_of(block)]
    for index, ch in ARROWS.items():
        rows = rows_of(mouse[index])
        font[ch] = [int(r[1:6].replace(".", "0").replace("#", "1"), 2) for r in rows[:7]]
    body = ",\n".join("%s:[%s]" % (repr(ch) if ch != "\\" else "'\\\\'", ",".join(map(str, rows)))
                      for ch, rows in font.items())
    with open(sys.argv[1], "w", encoding="utf-8") as f:
        f.write("// generated by web/font.py from src/machine/font.cpp\n")
        f.write('"use strict";\nconst APPLE_FONT = {\n' + body + "\n};\n")


if __name__ == "__main__":
    main()
